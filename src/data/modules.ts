export const MODULE_BY_ID = new Map(MODULES.map((m) => [m.id, m]))

export function moduleTitle(id: string): string {
  return MODULE_BY_ID.get(id)?.title ?? id
}

/** Titolo e obiettivo nella lingua scelta, con l'italiano come riserva. */
export function moduleTitleIn(module: ModuleSpec, language: 'it' | 'en'): string {
  return language === 'en' ? module.titleEn ?? module.title : module.title
}

export function moduleGoalIn(module: ModuleSpec, language: 'it' | 'en'): string {
  return language === 'en' ? module.goalEn ?? module.goal : module.goal
}
